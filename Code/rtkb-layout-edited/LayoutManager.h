/* 数量必须与 BUTTONCOUNT 一致（编译期检查） */
static_assert(sizeof(layout_custom) / sizeof(layout_custom[0]) == BUTTONCOUNT,
              "layout table must match BUTTONCOUNT");

/* 本固件提供自定义布局 */
#define LAYOUT_KIND LAYOUT_KIND_CUSTOM

/* 逐键上传布局：每键一帧 0xFE，序号沿用下发指令的 [7] */
void HIDLayoutUpload(const uint8_t *cmdBytes){
    for(uint8_t i = 0; i < BUTTONCOUNT; i++){
        KeyLayoutItem item;
        memcpy_P(&item, &layout_custom[i], sizeof(item));
        uint8_t resp[8] = { LAYOUT_FRAME_ITEM, i, item.x, item.y, item.w, item.h, item.flags, cmdBytes[7] };
        HID().SendReport(4, resp, 8);
    }
}

